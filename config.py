# ------------------------- 切片训练（原始分辨率） -------------------------
# 动机：`--size N` 的含义是「整张图缩到长边 N」。5472x3648 的图缩到 1024，原图 10px
# 宽的根只剩 1.9px —— 细根直接被抹掉，这是总长 −38.9% 的直接原因（见 tool/chain_diag）。
# 而「整图在原始分辨率上训练」在这个硬件上不可能：实测（tool/mem_probe）
#     5472x3648 batch1 要 116 GB；加梯度检查点 84 GB（只省 27%，因为全分辨率 skip
#     特征与 decoder 的 concat 是结构性的，省不掉）；24G 卡差 4.8 倍。
# 所以改成**从原图按原始分辨率随机裁块**训练 —— 同样 1280 个像素，块里的根就是 10px。
# 推理端模型是全卷积的，可以任意尺度跑（24G 实测：3648 约 18GB / 2736 约 10GB /
# 2048 约 5.7GB），所以推理侧不用改代码。
#
# ⚠️ 切片模型推理时**必须显式给 --size**（权重里记的 size 是训练时的块边长，不是推理
#    该用的尺度）。test.py / inference.py 会拦住不给的调用。
CROP_SIZE = 0            # 0 = 关闭（走整图缩放的老路径）；>0 = 块边长(px)，须是 16 的倍数
CROP_BG_PROB = 0.15      # 裁块时「纯随机位置」的概率；其余时候把块中心放在标注包围盒里，
                         # 避免大量块落在空白水域白跑。留这个口子是为了让模型也见到
                         # 纯背景，否则推理时容易在空白处产生假阳性。
CROP_REPEAT = 8          # 每张原图在一个 epoch 里抽多少个块。
                         # **这一项会决定训练能不能收敛**：不重复时一个 epoch 只有
                         # 「图片数」个样本（本项目 23 个，batch2 才 11 步 ≈ 4.5 秒），
                         # 而 LR 平台期(LR_PATIENCE=25)与早停(PATIENCE=120)都是按**轮**
