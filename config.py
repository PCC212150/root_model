# 软骨架的迭代次数。**这个值必须 ≥ 结构在模型分辨率下的最大半径，否则骨架退化成 0，
# 而骨架为 0 时 clDice 恰好 = 1、损失 = 0 —— 梯度静默消失，等于没开。**实测（等宽条）：
#   宽 2px 需 it≥1（硬标签）/ it≥3（软概率图）   ← 1024 下的根（根宽约 1.9px）
#   宽 4px 需 it≥1/ it≥5                        ← 2048 下的根（约 3.7px）
#   宽 8px 需 it≥3/ it≥10                       ← 靠近茎的根部团块
