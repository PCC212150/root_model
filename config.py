# ---- clDice：拓扑损失（Shit et al., CVPR 2021），只约束**骨架的连通性** ----
# 为什么加：本项目的根数误差是「拓扑」错，不是「像素」错 —— 实测两张测试图分别错在
# 并根（GT 45 根 → 预测 15，平均根长 347→936px）和断根（GT 43 根 → 预测 77，1407→638px），
# 而两边总根长都接近真值。断和并需要**相反**的阈值参数，后处理一套全局参数不可能同时修，
# 只能靠损失函数约束连通性。clDice 拿预测与真值的骨架算 Dice，断一段就扣分。
# 只给根系通道开（茎是实心圆盘，它的骨架是个点，没有意义）。全 0 = 关闭。
# **2026-09-15 实测结论：没起作用，默认关闭。** 三次开着 clDice 的训练
# （model_202609151924 / 1925 / 1956）验证 Dice 分别是 0.3917 / 0.4115 / 0.3485，
# **全部低于**不开 clDice 的 model_202609151347（0.4446）；其中 1956 还在 CK 批上
# 崩了（检查框内 86% 判成根，见 PRED_MAX_ROOT_RATIO 的说明）。
